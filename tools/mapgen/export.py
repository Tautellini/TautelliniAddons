"""Render one UI map and write it into the addon as TGA tiles.

Usage: py -3.13 export.py <uiMapID> <data_dir> <addon_dir> [clay|sand|slate]
Writes <addon_dir>/Tiles/<uiMapID>/<row>_<col>.tga and regenerates <addon_dir>/Tiles/Tiles.lua
with the tile grid of every map found under <addon_dir>/Tiles/.
"""
import os
import re
import sys

from PIL import Image

from preview import build, render

TILE_PX = 512  # power of two, as the client requires
COLS = 4


def write_index(tiles_dir):
    grids = {}
    for name in os.listdir(tiles_dir):
        if name.isdigit():
            cells = [tuple(map(int, m.groups())) for f in os.listdir(os.path.join(tiles_dir, name)) if (m := re.fullmatch(r"(\d+)_(\d+)\.tga", f))]
            grids[int(name)] = (max(r for r, _ in cells) + 1, max(c for _, c in cells) + 1)
    lines = ["-- Generated by tools/mapgen/export.py. Do not edit.", "local _, ns = ...", "ns.tiles = {"]
    lines += [f"    [{m}] = {{ rows = {r}, cols = {c} }}," for m, (r, c) in sorted(grids.items())]
    lines.append("}")
    open(os.path.join(tiles_dir, "Tiles.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    return grids


def main(ui_map_id, data_dir, addon_dir, style="clay"):
    masks = build(ui_map_id, data_dir)
    img = render(masks, style)
    left, top, right, bottom = masks["box"]
    rows = max(1, round(COLS * (bottom - top) / (right - left)))
    # The client stretches the tile grid over the map canvas, so resample the exact region to the grid.
    full = img.resize((COLS * TILE_PX, rows * TILE_PX), Image.LANCZOS, box=(left, top, right, bottom)).convert("RGBA")  # 32-bit TGA, the format addons commonly ship
    out = os.path.join(addon_dir, "Tiles", str(ui_map_id))
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        if f.endswith(".tga"):
            os.remove(os.path.join(out, f))
    for r in range(rows):
        for c in range(COLS):
            full.crop((c * TILE_PX, r * TILE_PX, (c + 1) * TILE_PX, (r + 1) * TILE_PX)).save(os.path.join(out, f"{r}_{c}.tga"))
    grids = write_index(os.path.join(addon_dir, "Tiles"))
    print(f"{ui_map_id}: {rows} x {COLS} tiles of {TILE_PX} px -> {out}. Maps with tiles: {sorted(grids)}")


if __name__ == "__main__":
    if len(sys.argv) not in (4, 5):
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
